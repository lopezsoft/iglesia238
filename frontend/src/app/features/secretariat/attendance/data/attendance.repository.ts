import { Observable } from 'rxjs';
import { Page } from '../../../../shared/utils/pagination';
import {
  AttendanceCount,
  AttendanceFilter,
  AttendanceListQuery,
  AttendanceOptions,
  AttendanceSession,
  AttendanceSessionInput,
  AttendanceSessionKey,
  AttendanceStats,
  AttendanceStatsQuery,
} from './attendance.models';

/**
 * Port of the attendance module (D-03). One session per sede, meeting type and date: creating
 * a second one fails with DomainError('DUPLICATE_SESSION') and the existing one is corrected
 * with `update`.
 */
export abstract class AttendanceRepository {
  /** Sedes of the active scope, meeting types, categories and today's date (server). */
  abstract options(): Observable<AttendanceOptions>;

  /** Sessions of the scope, most recent first, paged on the server. */
  abstract list(query: AttendanceListQuery): Observable<Page<AttendanceSession>>;

  /** The session recorded for the key, or null. */
  abstract find(key: AttendanceSessionKey): Observable<AttendanceSession | null>;

  abstract create(input: AttendanceSessionInput): Observable<AttendanceSession>;

  abstract update(id: number, counts: readonly AttendanceCount[]): Observable<AttendanceSession>;

  abstract remove(id: number): Observable<void>;

  abstract stats(query: AttendanceStatsQuery): Observable<AttendanceStats>;

  /** CSV of every session that matches the filter (generated by the API). */
  abstract exportCsv(filter: AttendanceFilter): Observable<Blob>;
}
