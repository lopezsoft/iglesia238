export const AUDIT_ENTITY_USER = 'User';
export const INVITATION_TTL_HOURS = 72;
/** A recovery link generated by an administrator is handed over by chat, not read from an inbox. */
export const ADMIN_RESET_TTL_HOURS = 24;
export const DISPLAY_NAME_MIN_LENGTH = 3;
export const DISPLAY_NAME_MAX_LENGTH = 150;
export const EMAIL_MAX_LENGTH = 191;

const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const HOUR_MS = 3_600_000;

/** The one-time link, shown only to the administrator who asked for it. */
export interface OneTimeLinkView {
  readonly link: string;
  readonly expiresAt: string;
  readonly purpose: LinkPurpose;
  /** True when the e-mail was handed to the mail server; false when the administrator must pass the link on. */
  readonly emailDelivered: boolean;
}

export interface InvitationResultView {
  readonly user: ManagedUserView;
  readonly invitation: OneTimeLinkView;
}

export interface InviteUserCommand {
  readonly context: TenantContext;
  readonly displayName: string;
  readonly email: string;
  readonly role: string;
  readonly denominationId: number | null;
  readonly congregationId: number | null;
  readonly ipAddress: string | null;
}

function invitationMessage(to: string, link: string) {
  return {
    to,
    kind: 'INVITATION',
    subject: 'Te invitaron a Iglesia 238',
    text: [
      'Te invitaron a usar Iglesia 238, el sistema de gestión de tu iglesia.',
      '',
      `Crea tu contraseña con este enlace (funciona una sola vez y vence en ${INVITATION_TTL_HOURS} horas):`,
      link,
      '',
      'Si no esperabas esta invitación, ignora este mensaje.',
    ].join('\n'),
    html: [
      '<p>Te invitaron a usar Iglesia 238, el sistema de gestión de tu iglesia.</p>',
      `<p>Crea tu contraseña con este enlace (funciona una sola vez y vence en ${INVITATION_TTL_HOURS} horas):</p>`,
      `<p><a href="${link}">Crear mi contraseña</a></p>`,
      '<p>Si no esperabas esta invitación, ignora este mensaje.</p>',
    ].join('\n'),
  };
}

function recoveryNoticeMessage(to: string) {
  return {
    to,
    kind: 'RECOVERY_NOTICE',
    subject: 'Se generó un enlace para cambiar tu contraseña',
    text: [
      'Un administrador de tu denominación generó un enlace de un solo uso para cambiar tu contraseña en Iglesia 238.',
      '',
      'Si no lo esperabas, avisa a tu administrador o al equipo de plataforma.',
    ].join('\n'),
    html: [
      '<p>Un administrador de tu denominación generó un enlace de un solo uso para cambiar tu contraseña en Iglesia 238.</p>',
      '<p>Si no lo esperabas, avisa a tu administrador o al equipo de plataforma.</p>',
    ].join('\n'),
  };
}

@Injectable()
export class InviteUserUseCase {
  constructor(
    @Inject(USER_DIRECTORY) private readonly users: UserDirectory,
    @Inject(ROLE_CATALOG) private readonly roles: RoleCatalog,
    @Inject(GRANT_SCOPE_READER) private readonly scopes: GrantScopeReader,
    @Inject(USER_LINK_STORE) private readonly links: UserLinkStore,
    @Inject(APP_LINKS) private readonly appLinks: AppLinks,
    @Inject(MAILER) private readonly mailer: Mailer,
    @Inject(TRANSACTION_RUNNER)
    private readonly transactions: TransactionRunner,
    @Inject(AUDIT_RECORDER) private readonly audit: AuditRecorder,
    private readonly clock: Clock,
  ) {}

  /**
   * Invites a NEW account. An e-mail that already belongs to an account is never attached to this
   * administrator's tenant from here: the person did not agree, and the answer would hand over data of
   * another tenant. Existing accounts receive roles through the grant endpoint (when they already
   * belong to the denomination) or through the platform team.
   */
  async execute(command: InviteUserCommand): Promise<InvitationResultView> {
    const manager = managerOf(command.context);
    const visibility = visibilityOf(manager);
    const displayName = this.validName(command.displayName);
    const email = this.validEmail(command.email);

    if (!(await this.roles.exists(command.role))) {
      throw new InvalidInputException('El rol no es válido.', 'INVALID_ROLE');
    }
    const existingId = await this.users.findIdByEmail(email);
    if (existingId !== null) {
      assertNotSelfGrant(manager, existingId);
      // The same answer for an account this administrator can see and for one that belongs to someone else.
      throw new ConflictDomainException(
        'Ya existe un usuario con ese correo electrónico.',
        'DUPLICATE_EMAIL',
      );
    }
    const scope = await resolveGrantScope(manager, command, this.scopes);

    const now = this.clock.now();
    const opaque = generateOpaqueToken();
    const expiresAt = new Date(now.getTime() + INVITATION_TTL_HOURS * HOUR_MS);

    const userId = await this.transactions.run(async (transaction) => {
      const id = await this.users.createInvitedUser(
        { email, displayName },
        transaction,
      );
      await this.links.replaceLink(
        {
          userId: id,
          purpose: 'INVITATION',
          tokenHash: opaque.hash,
          expiresAt,
        },
        now,
        transaction,
      );
      await this.audit.record(
        {
          action: 'USER_INVITED',
          entity: AUDIT_ENTITY_USER,
          entityId: id,
          actor: auditActorOf(manager),
          denominationId: scope.denominationId,
          congregationId: scope.congregationId,
          changes: buildAuditChanges(
            null,
            { invitationPending: true, role: command.role },
            ['invitationPending', 'role'],
          ),
          ipAddress: command.ipAddress,
        },
        transaction,
      );
      const assignmentId = await this.users.insertAssignment(
        {
          userId: id,
          roleCode: command.role,
          scope: scope.scope,
          denominationId: scope.denominationId,
          congregationId: scope.congregationId,
          scopeKey: scope.scopeKey,
          grantedById: manager.userId,
        },
        transaction,
      );
      await this.audit.record(
        {
          action: 'ROLE_GRANTED',
          entity: AUDIT_ENTITY_USER_ROLE,
          entityId: assignmentId,
          actor: auditActorOf(manager),
          denominationId: scope.denominationId,
          congregationId: scope.congregationId,
          changes: buildAuditChanges(
            null,
            { role: command.role, scopeKey: scope.scopeKey },
            ['role', 'scopeKey'],
          ),
          ipAddress: command.ipAddress,
        },
        transaction,
      );
      return id;
    });

    const user = await this.users.findVisible(visibility, userId);
    if (!user) {
      throw new NotFoundDomainException('El usuario no existe.');
    }

    const link = this.appLinks.invitation(opaque.token);
    // Delivery never throws; when it fails (or mail is not configured) the administrator shares the link.
    const { delivered } = await this.mailer.send(
      invitationMessage(email, link),
    );
    return {
      user: toManagedUserView(user, manager),
      invitation: {
        link,
        expiresAt: toIsoDateTime(expiresAt),
        purpose: 'INVITATION',
        emailDelivered: delivered,
      },
    };
  }

  private validName(raw: string): string {
    const name = collapseSpaces(raw);
    if (
      name.length < DISPLAY_NAME_MIN_LENGTH ||
      name.length > DISPLAY_NAME_MAX_LENGTH
    ) {
      throw new InvalidInputException(
        'Escribe el nombre completo de la persona.',
        'INVALID_NAME',
      );
    }
    return name;
  }

  private validEmail(raw: string): string {
    const email = raw.trim().toLowerCase();
    if (!EMAIL_PATTERN.test(email) || email.length > EMAIL_MAX_LENGTH) {
      throw new InvalidInputException(
        'Escribe un correo electrónico válido.',
        'INVALID_EMAIL',
      );
    }
    return email;
  }
}

export interface IssueUserLinkCommand {
  readonly context: TenantContext;
  readonly userId: number;
  readonly ipAddress: string | null;
}

/**
 * Link to set a password for an account: the invitation again for someone who never chose one, a
 * recovery link otherwise. It replaces any link still open and is returned only to the administrator.
 */
@Injectable()
export class IssueUserLinkUseCase {
  constructor(
    @Inject(USER_DIRECTORY) private readonly users: UserDirectory,
    @Inject(USER_LINK_STORE) private readonly links: UserLinkStore,
    @Inject(APP_LINKS) private readonly appLinks: AppLinks,
    @Inject(MAILER) private readonly mailer: Mailer,
    @Inject(TRANSACTION_RUNNER)
    private readonly transactions: TransactionRunner,
    @Inject(AUDIT_RECORDER) private readonly audit: AuditRecorder,
    private readonly clock: Clock,
  ) {}

  async execute(command: IssueUserLinkCommand): Promise<OneTimeLinkView> {
    const manager = managerOf(command.context);
    const user = await this.users.findVisible(
      visibilityOf(manager),
      command.userId,
    );
    if (!user) {
      throw new NotFoundDomainException(
        'El usuario no existe o no pertenece a tu denominación.',
      );
    }
    // A link opens the account: only the platform may issue one for an account that has worked (or
    // works) outside this denomination, even if those roles were revoked.
    if (!manager.isPlatformAdmin && user.hasHiddenAssignments) {
      throw new ForbiddenDomainException(
        'Esta cuenta tiene o tuvo roles fuera de tu denominación: solo el equipo de plataforma puede generar su enlace.',
        'ACCOUNT_SHARED',
      );
    }
    // Nor may an administrator take over a peer: administrators recover through the platform team.
    if (
      !manager.isPlatformAdmin &&
      user.id !== manager.userId &&
      user.assignments.some(
        (assignment) =>
          assignment.revokedAt === null &&
          ADMIN_ROLE_CODES.includes(assignment.roleCode),
      )
    ) {
      throw new ForbiddenDomainException(
        'No puedes generar el enlace de otro administrador: solicítalo al equipo de plataforma.',
        'ACCOUNT_PROTECTED',
      );
    }
    if (!user.isActive) {
      throw new ConflictDomainException(
        'La cuenta está inactiva.',
        'USER_INACTIVE',
      );
    }

    const purpose: LinkPurpose = user.hasPassword
      ? 'PASSWORD_RESET'
      : 'INVITATION';
    const ttlHours =
      purpose === 'INVITATION' ? INVITATION_TTL_HOURS : ADMIN_RESET_TTL_HOURS;
    const now = this.clock.now();
    const expiresAt = new Date(now.getTime() + ttlHours * HOUR_MS);
    const opaque = generateOpaqueToken();

    await this.transactions.run(async (transaction) => {
      await this.links.replaceLink(
        { userId: user.id, purpose, tokenHash: opaque.hash, expiresAt },
        now,
        transaction,
      );
      await this.audit.record(
        {
          action: 'USER_LINK_ISSUED',
          entity: AUDIT_ENTITY_USER,
          entityId: user.id,
          actor: auditActorOf(manager),
          changes: buildAuditChanges(null, { purpose }, ['purpose']),
          ipAddress: command.ipAddress,
        },
        transaction,
      );
    });

    if (purpose === 'PASSWORD_RESET') {
      // The holder is told that someone generated the link. The notice carries no link or token.
      await this.mailer.send(recoveryNoticeMessage(user.email));
    }

    return {
      link:
        purpose === 'INVITATION'
          ? this.appLinks.invitation(opaque.token)
          : this.appLinks.passwordReset(opaque.token),
      expiresAt: toIsoDateTime(expiresAt),
      purpose,
      emailDelivered: false,
    };
  }
}
